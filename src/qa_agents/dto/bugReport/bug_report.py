from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from qa_agents.dto.bugReport.environment import Environment

Priority = Literal["blocker", "critical", "high", "low"]


class BugReport(BaseModel):
    """Баг-репорт, составленный по описанию из чата.
    Правила: пиши по-русски; один отчёт описывает один дефект; используй только факты из описания
    и ничего не выдумывай; формулировки конкретные, слова вроде «не работает» или «глючит»
    без уточнения, что именно происходит, не допускаются."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    title: str = Field(
        min_length=10,
        max_length=80,
        description=(
            "Одно предложение длиной 10-80 символов, отвечающее на вопросы: Что сломалось? Где "
            "(экран, функция, платформа)? При каком действии? Без точки в конце, без версии и стенда."
        ),
        examples=["Кнопка «Перевести» не реагирует на нажатие в форме перевода на Android"],
    )
    steps: list[tuple[int, str]] = Field(
        min_length=1,
        max_length=15,
        description=(
            "Шаги воспроизведения в порядке выполнения: список пар [номер, текст], нумерация с 1 "
            "подряд без пропусков. Один шаг это одно действие в повелительном наклонении "
            "(«Открыть…», «Нажать…»). Начни с открытия экрана или предусловия, закончи действием, "
            "после которого виден дефект. Результат в шаги не включай."
        ),
        examples=[[[1, "Открыть форму перевода"], [2, "Нажать кнопку «Перевести»"]]],
    )
    expected: str | None = Field(
        description=(
            "Ожидаемый результат: как система должна работать по требованиям или здравому смыслу, "
            "одно предложение в настоящем времени. Если из описания определить нельзя, верни строку "
            "{должен заполнить тестировщик} и ничего не придумывай."
        ),
    )
    actual: str = Field(
        description=(
            "Фактический результат: что происходит на самом деле, фактами и без оценок "
            "(«выглядит странно» и «глючит» не годятся). Включи наблюдаемое поведение и, если есть, "
            "код ошибки."
        ),
    )
    logs: str | None = Field(
        description=(
            "Дословный фрагмент логов, стектрейса или текста ошибки из описания, скопированный без "
            "изменений. Если в описании логов нет, верни null. Логи не сочиняй."
        ),
    )
    environment: Environment = Field(
        description="Среда обнаружения дефекта: где виден, версия и стенд.",
    )
    priority: Priority = Field(
        description=(
            "Приоритет исправления по влиянию на пользователей и бизнес. "
            "blocker: система или ключевой сценарий полностью недоступны, обходного пути нет. "
            "critical: ключевая функция не работает или есть риск потери денег и данных, но система жива. "
            "high: функция работает неверно, есть обходной путь. "
            "low: косметика, опечатки, мелкие неудобства. "
            "Выбирай по описанному влиянию, а не по эмоциям автора."
        ),
    )
    evidence: str = Field(
        min_length=1,
        description=(
            "Дословная цитата из описания (скопируй без изменений, не пересказывай), на которой "
            "основаны фактический результат и приоритет. Если в описании есть логи, цитируй ключевую "
            "строку лога, иначе цитируй фразу автора."
        ),
    )
    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description=(
            "Уверенность в отчёте от 0 до 1. 0.9 и выше: все поля прямо следуют из текста. "
            "От 0.6 до 0.8: часть полей выведена по смыслу. Ниже 0.6: данных мало или описание "
            "противоречиво."
        ),
    )

    @field_validator("steps")
    @classmethod
    def steps_are_numbered_from_one(cls, steps: list[tuple[int, str]]) -> list[tuple[int, str]]:
        """Проверка после ответа модели: нумерация с 1 без пропусков и непустой текст шага."""
        if [number for number, _ in steps] != list(range(1, len(steps) + 1)):
            raise ValueError("Шаги должны быть пронумерованы с 1 подряд без пропусков")
        if any(not text.strip() for _, text in steps):
            raise ValueError("Текст шага не должен быть пустым")
        return steps
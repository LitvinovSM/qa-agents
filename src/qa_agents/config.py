"""Настройки проекта в одном месте.

Аналогия с Java/Spring: это как application.properties + класс с константами.
Все остальные файлы берут настройки ОТСЮДА, а не пишут адреса и имена
моделей у себя. Поменял здесь — поменялось везде.
"""

# `import os` — подключаем стандартный модуль os (работа с операционной системой).
# Аналог Java: `import java.lang.System;` — нам нужен доступ к переменным окружения.
import os

# -----------------------------------------------------------------------------
# Адрес сервера Ollama.
#
# os.getenv("ИМЯ", "значение_по_умолчанию") читает переменную окружения.
# Если переменной нет — возвращает значение по умолчанию.
# Аналог Java: System.getenv().getOrDefault("OLLAMA_BASE_URL", "http://...").
#
# Зачем так: локально Ollama живёт на localhost, а на Дне 7 внутри Docker
# адрес будет другой (host.docker.internal). Код менять не придётся —
# только переменную окружения.
#
# Запись `: str` после имени — это ПОДСКАЗКА ТИПА (type hint).
# Python её НЕ проверяет при запуске, она для тебя, IDE и mypy.
# Аналог Java: `String OLLAMA_BASE_URL = ...`.
#
# Имена ЗАГЛАВНЫМИ БУКВАМИ — договорённость «это константа, не меняй».
# В Python нет слова final, это просто соглашение.
# -----------------------------------------------------------------------------
OLLAMA_BASE_URL: str = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")

# Основная модель агентов. Выбрана по твоему замеру:
# 4b — 3 из 3 правильных ответа, ~5 секунд на короткий ответ.
DEFAULT_MODEL: str = "qwen3.5:4b"

# Быстрая, но менее точная модель. Пригодится для сравнения на Дне 6.
FAST_MODEL: str = "qwen3.5:2b"

# Сколько секунд ждать ответа от сервера, прежде чем сдаться.
# Для служебных запросов (версия, список моделей) 10 секунд — с запасом.
# Аналог: RestAssured .config(...connectionTimeout...).
REQUEST_TIMEOUT_SECONDS: int = 10

# Сколько видеопамяти у твоей карты (GTX 1650). Нужно для задания про VRAM.
GPU_VRAM_GB: float = 4.0
